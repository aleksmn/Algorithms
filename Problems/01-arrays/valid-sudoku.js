// Вам дано поле Судоку размером 9×9. Поле считается корректным, если выполняются следующие правила:

// В каждой строке не должно быть повторяющихся цифр от 1 до 9.
// В каждом столбце не должно быть повторяющихся цифр от 1 до 9.
// В каждом из девяти подблоков 3×3 не должно быть повторяющихся цифр от 1 до 9.
// Верните true, если поле корректно, иначе false.

// Примечание: поле не обязано быть заполнено полностью и не обязательно разрешимо, чтобы считаться корректным.

// Пример:

// Ввод:
// [["1","2",".",".","3",".",".",".","."],
// ["4",".",".","5",".",".",".",".","."],
// [".","9","8",".",".",".",".",".","3"],
// ["5",".",".",".","6",".",".",".","4"],
// [".",".",".","8",".","3",".",".","5"],
// ["7",".",".",".","2",".",".",".","6"],
// [".",".",".",".",".",".","2",".","."],
// [".",".",".","4","1","9",".",".","8"],
// [".",".",".",".","8",".",".","7","9"]]

// Вывод: true


function isValidSudoku(board) {
    const rows = Array.from({ length: 9 }, () => new Set());
    const cols = Array.from({ length: 9 }, () => new Set());
    const boxes = Array.from({ length: 9 }, () => new Set());

    for (let i = 0; i < 9; i++) {
        for (let j = 0; j < 9; j++) {
            const val = board[i][j];
            if (val === '.' || val === 0) continue;
            if (val < '1' || val > '9') return false;
            const boxIdx = Math.floor(i / 3) * 3 + Math.floor(j / 3);
            if (rows[i].has(val) || cols[j].has(val) || boxes[boxIdx].has(val)) {
                return false;
            }
            rows[i].add(val);
            cols[j].add(val);
            boxes[boxIdx].add(val);
        }
    }
    return true;
}